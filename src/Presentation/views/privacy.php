    <p>Implementamos medidas de seguridad técnicas y organizativas para proteger sus datos personales contra accesos no autorizados, pérdida o alteración. Sus contraseñas se almacenan cifradas y las comunicaciones se realizan mediante conexiones seguras.</p>

